'use strict';

const fs = require('fs');
const path = require('path');

const pkg = require('../package.json');
const base = String(pkg.version || '1.0.0');
const stamp = new Date().toISOString().slice(0, 10).replace(/-/g, '');
const ver = `${base}-${stamp}`;
const out = path.join(__dirname, '..', 'public', 'asset-version.js');
const code = `/* auto-generated by npm run build — do not edit by hand */\nwindow.__ASSET_VER=${JSON.stringify(ver)};\n`;
fs.writeFileSync(out, code, 'utf8');
console.log('Wrote', out, '→', ver);
